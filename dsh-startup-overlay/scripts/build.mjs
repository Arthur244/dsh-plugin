import { readFile, writeFile } from 'node:fs/promises'

const source = await readFile(new URL('../src/client.js', import.meta.url), 'utf8')
const body = source.replace(/^export const inject =/m, 'const inject =')
  .replace(/^export (async )?function (waitForStartup|apply)\(/gm, '$1function $2(')
if (/^(?:import|export)\s/m.test(body)) throw new Error('Client source must remain self-contained')
const output = `// Generated by scripts/build.mjs from src/client.js. Do not edit directly.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-startup-overlay',\n  factory() {\n${body.split('\n').map(line => line ? `    ${line}` : '').join('\n')}    return { name: 'dsh-startup-overlay', inject, apply }\n  },\n})\n`
const target = new URL('../client.js', import.meta.url)
let existing
try {
  existing = await readFile(target, 'utf8')
} catch (error) {
  if (error.code !== 'ENOENT') throw error
}
if (process.argv.includes('--check')) {
  if (existing !== output) throw new Error('client.js is stale; run npm run build')
} else if (existing !== output) {
  await writeFile(target, output)
}
